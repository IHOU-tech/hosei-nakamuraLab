#include <math.h>
#include <stdio.h>
#include <unistd.h>
#include <ypspur.h>

int main(int argc, char *argv[])
{
    double x, y, theta;

    setvbuf(stdout, 0, _IONBF, 0);

    // YP-Spur初期化
    if (Spur_init() < 0)
    {
        fprintf(stderr, "ERROR : cannot open spur.\n");
        return -1;
    }

    // 走行速度・加速度
    Spur_set_vel(0.2);
    Spur_set_accel(0.5);

    // 旋回速度・角加速度
    Spur_set_angvel(M_PI / 2.0);
    Spur_set_angaccel(M_PI / 2.0);

    // 初期位置：(0, 0)
    // 初期姿勢：上方向（+Y）= π/2
    Spur_set_pos_GL(
        0.0,
        0.0,
        M_PI / 2.0
    );

    printf("Figure-8 trajectory test start\n");


    // ========================================
    // 1. 上： (0,0) -> (0,1)
    // ========================================

    printf("1 : UP    (0,0) -> (0,1)\n");

    // y = 1.005 m で停止
    Spur_stop_line_GL(
        0.0,
        1.0 + 0.005,
        M_PI / 2.0
    );

    // y = 1.0 m を越えるまで待機
    while (!Spur_over_line_GL(
        0.0,
        1.0,
        M_PI / 2.0))
    {
        usleep(100000);
    }

    Spur_stop();


    // ========================================
    // 右を向く
    // ========================================

    Spur_spin_GL(0.0);

    while (!Spur_near_ang_GL(
        0.0,
        M_PI / 180.0))
    {
        usleep(100000);
    }


    // ========================================
    // 2. 右： (0,1) -> (1,1)
    // ========================================

    printf("2 : RIGHT (0,1) -> (1,1)\n");

    Spur_stop_line_GL(
        1.0 + 0.005,
        1.0,
        0.0
    );

    while (!Spur_over_line_GL(
        1.0,
        1.0,
        0.0))
    {
        usleep(100000);
    }

    Spur_stop();


    // ========================================
    // 上を向く
    // ========================================

    Spur_spin_GL(M_PI / 2.0);

    while (!Spur_near_ang_GL(
        M_PI / 2.0,
        M_PI / 180.0))
    {
        usleep(100000);
    }


    // ========================================
    // 3. 上： (1,1) -> (1,2)
    // ========================================

    printf("3 : UP    (1,1) -> (1,2)\n");

    Spur_stop_line_GL(
        1.0,
        2.0 + 0.005,
        M_PI / 2.0
    );

    while (!Spur_over_line_GL(
        1.0,
        2.0,
        M_PI / 2.0))
    {
        usleep(100000);
    }

    Spur_stop();


    // ========================================
    // 左を向く
    // ========================================

    Spur_spin_GL(M_PI);

    while (!Spur_near_ang_GL(
        M_PI,
        M_PI / 180.0))
    {
        usleep(100000);
    }


    // ========================================
    // 4. 左： (1,2) -> (0,2)
    // ========================================

    printf("4 : LEFT  (1,2) -> (0,2)\n");

    // -X方向なので x = -0.005 m が停止ライン
    Spur_stop_line_GL(
        -0.005,
        2.0,
        M_PI
    );

    // x = 0.0 m を越えるまで待機
    while (!Spur_over_line_GL(
        0.0,
        2.0,
        M_PI))
    {
        usleep(100000);
    }

    Spur_stop();


    // ========================================
    // 下を向く
    // ========================================

    Spur_spin_GL(-M_PI / 2.0);

    while (!Spur_near_ang_GL(
        -M_PI / 2.0,
        M_PI / 180.0))
    {
        usleep(100000);
    }


    // ========================================
    // 5. 下： (0,2) -> (0,1)
    // ========================================

    printf("5 : DOWN  (0,2) -> (0,1)\n");

    // -Y方向なので目標 y=1.0 より5 mm先
    Spur_stop_line_GL(
        0.0,
        1.0 - 0.005,
        -M_PI / 2.0
    );

    while (!Spur_over_line_GL(
        0.0,
        1.0,
        -M_PI / 2.0))
    {
        usleep(100000);
    }

    Spur_stop();


    // ========================================
    // 左を向く
    // ========================================

    Spur_spin_GL(M_PI);

    while (!Spur_near_ang_GL(
        M_PI,
        M_PI / 180.0))
    {
        usleep(100000);
    }


    // ========================================
    // 6. 左： (0,1) -> (-1,1)
    // ========================================

    printf("6 : LEFT  (0,1) -> (-1,1)\n");

    // 目標 -1.0 m よりさらに5 mm先
    Spur_stop_line_GL(
        -1.0 - 0.005,
        1.0,
        M_PI
    );

    while (!Spur_over_line_GL(
        -1.0,
        1.0,
        M_PI))
    {
        usleep(100000);
    }

    Spur_stop();


    // ========================================
    // 下を向く
    // ========================================

    Spur_spin_GL(-M_PI / 2.0);

    while (!Spur_near_ang_GL(
        -M_PI / 2.0,
        M_PI / 180.0))
    {
        usleep(100000);
    }


    // ========================================
    // 7. 下： (-1,1) -> (-1,0)
    // ========================================

    printf("7 : DOWN  (-1,1) -> (-1,0)\n");

    Spur_stop_line_GL(
        -1.0,
        -0.005,
        -M_PI / 2.0
    );

    while (!Spur_over_line_GL(
        -1.0,
        0.0,
        -M_PI / 2.0))
    {
        usleep(100000);
    }

    Spur_stop();


    // ========================================
    // 右を向く
    // ========================================

    Spur_spin_GL(0.0);

    while (!Spur_near_ang_GL(
        0.0,
        M_PI / 180.0))
    {
        usleep(100000);
    }


    // ========================================
    // 8. 右： (-1,0) -> (0,0)
    // ========================================

    printf("8 : RIGHT (-1,0) -> (0,0)\n");

    Spur_stop_line_GL(
        0.005,
        0.0,
        0.0
    );

    while (!Spur_over_line_GL(
        0.0,
        0.0,
        0.0))
    {
        usleep(100000);
    }

    Spur_stop();


    // ========================================
    // 最終オドメトリ表示
    // ========================================

    Spur_get_pos_GL(
        &x,
        &y,
        &theta
    );

    printf("\nFigure-8 test finished\n");

    printf(
        "Final odometry: "
        "x = %.3f m, "
        "y = %.3f m, "
        "theta = %.3f rad\n",
        x,
        y,
        theta
    );

    Spur_free();

    return 0;
}